import os, sys, requests
from matplotlib import use as mpl_use
mpl_use("Agg")
import matplotlib.pyplot as plt
from matplotlib.mathtext import math_to_image
import numpy as np
from fpdf import FPDF
import config

TOKEN = config.TELEGRAM_TOKEN
ADMIN_ID = getattr(config, "ADMIN_CHAT_ID", 8857708587)

os.makedirs("pdf_test_assets", exist_ok=True)

# 1. Formula PNGs
formulas = [
    (r"$E = h\nu = \frac{hc}{\lambda}$", "pdf_test_assets/f1.png"),
    (r"$\tau = rF\sin\theta$",           "pdf_test_assets/f2.png"),
    (r"$\int_0^\infty e^{-x}dx = 1$",    "pdf_test_assets/f3.png"),
]
for tex, path in formulas:
    math_to_image(tex, path, dpi=250, format="png")
print("formulas rendered")

# 2. EM wave diagram
x = np.linspace(0, 4*np.pi, 400)
fig, ax = plt.subplots(figsize=(7, 3))
ax.plot(x, np.sin(x),         color="#d62728", linewidth=2, label="E field")
ax.plot(x, np.sin(x - np.pi/2), color="#1f77b4", linewidth=2, label="B field")
ax.axhline(0, color="black", linewidth=0.5)
ax.set_title("Electromagnetic Wave (E ⊥ B ⊥ direction)")
ax.set_xlabel("Position →"); ax.set_ylabel("Amplitude")
ax.legend(loc="upper right", fontsize=9)
ax.grid(True, alpha=0.3)
fig.tight_layout()
fig.savefig("pdf_test_assets/em_wave.png", dpi=150, bbox_inches="tight")
plt.close(fig)
print("diagram rendered")

# 3. Build PDF
pdf = FPDF()
pdf.add_page()
pdf.add_font("DejaVu", "", "DejaVuSans.ttf")

pdf.set_font("DejaVu", size=16)
pdf.cell(0, 12, "Hamilton Study AI — PDF Test", new_x="LMARGIN", new_y="NEXT")
pdf.set_font("DejaVu", size=10)
pdf.cell(0, 6, "Generated by Hamilton  •  Test only", new_x="LMARGIN", new_y="NEXT")
pdf.ln(4)

pdf.set_font("DejaVu", size=12)
pdf.cell(0, 8, "1. Unicode sanity check", new_x="LMARGIN", new_y="NEXT")
pdf.set_font("DejaVu", size=11)
pdf.multi_cell(0, 6, "Symbols: θ τ π √ ≈ × ∫ ∑ ± ≤ ≥ α β γ Δ ∞ ⇒")
pdf.ln(3)

pdf.set_font("DejaVu", size=12)
pdf.cell(0, 8, "2. Formulas (embedded as PNG)", new_x="LMARGIN", new_y="NEXT")
pdf.image("pdf_test_assets/f1.png", w=70); pdf.ln(1)
pdf.image("pdf_test_assets/f2.png", w=45); pdf.ln(1)
pdf.image("pdf_test_assets/f3.png", w=70); pdf.ln(3)

pdf.add_page()
pdf.set_font("DejaVu", size=12)
pdf.cell(0, 8, "3. Diagram (matplotlib)", new_x="LMARGIN", new_y="NEXT")
pdf.image("pdf_test_assets/em_wave.png", w=175)
pdf.ln(2)
pdf.set_font("DejaVu", size=10)
pdf.multi_cell(0, 5, "EM waves: E and B oscillate in phase, both perpendicular to the direction of propagation.")

pdf.output("pdf_test_assets/hamilton_test.pdf")
size = os.path.getsize("pdf_test_assets/hamilton_test.pdf")
print(f"PDF built: {size} bytes")

# 4. Send via Telegram
url = f"https://api.telegram.org/bot{TOKEN}/sendDocument"
with open("pdf_test_assets/hamilton_test.pdf", "rb") as f:
    r = requests.post(
        url,
        data={"chat_id": ADMIN_ID, "caption": "🧪 Hamilton PDF Test — 2 pages, font + formula + diagram"},
        files={"document": f},
        timeout=60,
    )
print(f"Telegram HTTP status: {r.status_code}")
resp = r.json()
print(f"Sent: {resp.get('ok')}")
if resp.get("ok"):
    print(f"message_id: {resp['result']['message_id']}")
else:
    print(f"error: {resp.get('description')}")
